"""Generate keys and configuration for a docker compose deployment (synthetic register).

    .venv/bin/python deploy/setup.py            # writes deploy/config/ and deploy/keycloak/realm.json

In a real consortium every key is generated by the party that holds it (the issuer its RSA key,
each member its witness and trustee keys) and only public keys are exchanged. Here one script
writes all of them for convenience; deploy/config/ is git-ignored.
"""
from __future__ import annotations

import json
import random
import secrets
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from anonsurv import alerts, ohttp, synth, tlog  # noqa: E402
from anonsurv import rsabssa as bs  # noqa: E402

HERE = Path(__file__).parent
CFG = HERE / "config"
MEMBERS = ["member-1", "member-2", "member-3"]
N_TRUSTEES, T = 5, 3


def main():
    CFG.mkdir(exist_ok=True)
    register = synth.register(random.Random(7))
    (CFG / "register.json").write_text(json.dumps([asdict(c) for c in register.values()], indent=1))

    sk = bs.SecretKey.generate(2048)
    (CFG / "issuer_sk.pem").write_bytes(sk.to_pem())
    (CFG / "issuer_pk.pem").write_bytes(sk.public_key.to_pem())
    (CFG / "lab_key").write_text(secrets.token_hex(16))

    log_sk = tlog.Ed25519PrivateKey.generate()
    (CFG / "log_sk").write_text(log_sk.private_bytes_raw().hex())
    wit = {}
    for m in MEMBERS:
        w = tlog.Ed25519PrivateKey.generate()
        (CFG / f"witness_{m}_sk").write_text(w.private_bytes_raw().hex())
        wit[m] = tlog.ed25519_pub_hex(w)
    (CFG / "anchors.json").write_text(json.dumps({"log_pub": tlog.ed25519_pub_hex(log_sk), "witnesses": wit,
                                                  "quorum": 2}, indent=1))

    trustees = [alerts.new_keypair() for _ in range(N_TRUSTEES)]
    (CFG / "escrow.json").write_text(json.dumps({"trustees": [pk.hex() for _, pk in trustees], "t": T, "k": 8}))
    for i, (tsk, _) in enumerate(trustees, 1):
        (CFG / f"trustee_{i}_sk").write_text(tsk.hex())

    gsk = secrets.token_bytes(32)
    (CFG / "gateway_sk").write_text(gsk.hex())
    (CFG / "ohttp_keys.bin").write_bytes(ohttp.Gateway(gsk).keys())

    users = [{"username": cid.lower(), "enabled": True, "email": f"{cid.lower()}@example.invalid",
              "emailVerified": True, "firstName": "Legal", "lastName": f"Representative {cid}",
              "attributes": {"ivaCode": [f"VATIT-{c.vat}"]},
              "credentials": [{"type": "password", "value": f"pw-{cid}", "temporary": False}]}
             for cid, c in register.items()]
    users.append({"username": "notafbo", "enabled": True, "email": "notafbo@example.invalid", "emailVerified": True,
                  "firstName": "Not", "lastName": "AnFBO", "attributes": {"ivaCode": ["VATIT-99999999999"]},
                  "credentials": [{"type": "password", "value": "pw-notafbo", "temporary": False}]})
    profile = {"unmanagedAttributePolicy": "ENABLED",
               "attributes": [{"name": n, "displayName": n, "permissions": {"view": ["admin"], "edit": ["admin"]},
                               "validations": {}} for n in ("username", "email", "firstName", "lastName")]}
    realm = {
        "realm": "anonsurv", "enabled": True,
        "components": {"org.keycloak.userprofile.UserProfileProvider": [{
            "providerId": "declarative-user-profile",
            "config": {"kc.user.profile.config": [json.dumps(profile)]}}]},
        "clients": [{
            "clientId": "anonsurv-issuer", "publicClient": True, "directAccessGrantsEnabled": True,
            "standardFlowEnabled": True, "redirectUris": ["http://localhost/*"],
            "protocolMappers": [{
                "name": "ivaCode", "protocol": "openid-connect", "protocolMapper": "oidc-usermodel-attribute-mapper",
                "config": {"user.attribute": "ivaCode", "claim.name": "ivaCode", "jsonType.label": "String",
                           "id.token.claim": "true", "access.token.claim": "false", "userinfo.token.claim": "true"}}]}],
        "users": users}
    (HERE / "keycloak").mkdir(exist_ok=True)
    (HERE / "keycloak" / "realm.json").write_text(json.dumps(realm, indent=1))
    print(f"wrote {CFG}/ ({len(register)} companies, {len(MEMBERS)} witnesses, {N_TRUSTEES} trustees) "
          f"and keycloak/realm.json")


if __name__ == "__main__":
    main()
